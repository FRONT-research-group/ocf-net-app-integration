reusable_oauth2 = OAuth2PasswordBearer(
    tokenUrl=f"{settings.API_V1_STR}/login/access-token"
)

#Dependencies
def get_db() -> Generator:
    try:
        db = SessionLocal() #Only the code prior to and including the yield statement is executed before sending a response
        yield db            #The yielded value is what is injected into path operations and other dependencies
    finally:
        db.close()          #The code following the yield statement is executed after the response has been delivered

def verify_with_public_key(token: str = Depends(reusable_oauth2)):
    '''
    Enable verification of a token generated by CAPIF for an API Invoker.
    If env variable USE_PUBLIC_KEY_VERIFICATION is set to False, the verification is ommited.
    '''
    if settings.USE_PUBLIC_KEY_VERIFICATION == True:
        try:
            payload = jwt.decode(
                token, security.extract_public_key('/app/app/core/certificates/capif_cert_server.pem'), algorithms=[security.ALGORITHM[1]]
            )
        except (jwt.JWTError):
            raise HTTPException(
                status_code=status.HTTP_401_UNAUTHORIZED,
                detail="Could not validate credentials - Token from CAPIF",
            )
        return payload
    else:
        return None


def verify_capif_api_scope(
    payload: dict,
    expected_api_name: str,
):
    """
    Verify that a CAPIF JWT is authorized for the expected API.

    CAPIF scope format used by this deployment:
        <scope-prefix>:<api-name>

    Example:
        3gpp#AEF123...:<api-name>
    """

    if not expected_api_name:
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail="Expected CAPIF API name is not configured",
        )

    if not isinstance(payload, dict):
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Could not validate CAPIF token payload",
        )

    scope_claim = payload.get("scope", "")

    if not isinstance(scope_claim, str):
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail="CAPIF token has no valid API scope",
        )

    # CAPIF may provide one or more space-separated scope values.
    for scope in scope_claim.split():
        if ":" not in scope:
            continue

        _, scoped_api_name = scope.rsplit(":", 1)

        if scoped_api_name == expected_api_name:
            return payload

    raise HTTPException(
        status_code=status.HTTP_403_FORBIDDEN,
        detail="CAPIF token is not authorized for this API",
    )


def verify_monitoring_event_scope(
    payload: dict = Depends(verify_with_public_key),
):
    """
    CAPIF authorization dependency for MonitoringEvent.
    """
    return verify_capif_api_scope(
        payload,
        os.getenv("CAPIF_MONITORING_EVENT_API_NAME"),
    )


def verify_session_with_qos_scope(
    payload: dict = Depends(verify_with_public_key),
):
    """
    CAPIF authorization dependency for Session-with-QoS.
    """
    return verify_capif_api_scope(
        payload,
        os.getenv("CAPIF_SESSION_WITH_QOS_API_NAME"),
    )


def get_current_user(
    db: Session = Depends(get_db), token: str = Depends(reusable_oauth2)
) -> models.User:
    '''
    Enable verification of a token generated by CAPIF for an API Invoker.
    If env variable USE_PUBLIC_KEY_VERIFICATION is set to False, NEF verifies the access token acquired from NEF.
    Else NEF vefirication token is ommited and the function returns the default user
    '''
    if settings.USE_PUBLIC_KEY_VERIFICATION == False:
        try:
            payload = jwt.decode(
                token, settings.SECRET_KEY, algorithms=[security.ALGORITHM[0]]
            )
            token_data = schemas.TokenPayload(**payload)
        except (jwt.JWTError, ValidationError):
            raise HTTPException(
                status_code=status.HTTP_401_UNAUTHORIZED,
                detail="Could not validate credentials - Token from NEF",
            )
        user = crud.user.get(db, id=token_data.sub)
        if not user:
            raise HTTPException(status_code=404, detail="User not found")
        return user
    else:
        user = crud.user.get_by_email(db, email="admin@my-email.com")
        return user


def get_current_active_user(
    current_user: models.User = Depends(get_current_user),
) -> models.User:
    if not crud.user.is_active(current_user):
        raise HTTPException(status_code=400, detail="Inactive user")
    return current_user


def get_current_active_superuser(
    current_user: models.User = Depends(get_current_user),
) -> models.User:
    if not crud.user.is_superuser(current_user):
        raise HTTPException(
            status_code=400, detail="The user doesn't have enough privileges"
        )
    return current_user
